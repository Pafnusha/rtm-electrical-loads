function clamp(x, a, b) {
  return Math.max(a, Math.min(b, x));
}

function findBracket(sorted, x) {
  if (x <= sorted[0]) return [0, 0];
  const n = sorted.length;
  if (x >= sorted[n - 1]) return [n - 1, n - 1];
  let i = 0;
  while (i < n - 1 && sorted[i + 1] < x) i++;
  return [i, i + 1];
}

function lerp(a, b, t) {
  return a + (b - a) * t;
}

/**
 * Билинейная интерполяция по табл. 1.
 * @param {number} ne эффективное число ЭП
 * @param {number} ki средневзвешенный Ки
 * @returns {number} Кр
 */
export function lookupKrTable1(ne, ki) {
  if (!(ne > 0) || !(ki >= 0)) return 1.0;
  // По примечаниям РТМ / структуре табл.1: при Ки ≥ 0.8 Кр = 1.0
  if (ki >= 0.8) return 1.0;

  const neVals = TABLE1.ne;
  const kiVals = KI_COLS_T1;
  const [i0, i1] = findBracket(neVals, ne);
  const [j0, j1] = findBracket(kiVals, ki);

  const ne0 = neVals[i0];
  const ne1 = neVals[i1];
  const ki0 = kiVals[j0];
  const ki1 = kiVals[j1];

  const tNe = ne1 === ne0 ? 0 : (ne - ne0) / (ne1 - ne0);
  const tKi = ki1 === ki0 ? 0 : (ki - ki0) / (ki1 - ki0);

  const v00 = TABLE1.rows[i0][j0];
  const v10 = TABLE1.rows[i1][j0];
  const v01 = TABLE1.rows[i0][j1];
  const v11 = TABLE1.rows[i1][j1];

  const v0 = lerp(v00, v10, tNe);
  const v1 = lerp(v01, v11, tNe);
  return lerp(v0, v1, tKi);
}

/**
 * Поиск Кр по табл. 2: дискретный диапазон nэ + линейная интерполяция по Ки.
 */
export function lookupKrTable2(ne, ki) {
  if (!(ne > 0) || !(ki >= 0)) return 1.0;
  const n = Math.max(1, ne);
  let rowIdx = TABLE2.ranges.length - 1;
  for (let i = 0; i < TABLE2.ranges.length; i++) {
    const r = TABLE2.ranges[i];
    if (n >= r.lo && n <= r.hi) {
      rowIdx = i;
      break;
    }
  }
  const row = TABLE2.rows[rowIdx];
  const kiVals = KI_COLS_T2;
  // Последний столбец — «0,7 и более»
  if (ki >= 0.7) return row[row.length - 1];
  if (ki <= kiVals[0]) return row[0];

  const [j0, j1] = findBracket(kiVals, ki);
  const ki0 = kiVals[j0];
  const ki1 = kiVals[j1];
  const t = ki1 === ki0 ? 0 : (ki - ki0) / (ki1 - ki0);
  return lerp(row[j0], row[j1], t);
}

/**
 * @param {'table1'|'table2'} mode
 * @param {number} ne
 * @param {number} ki
 */
export function lookupKr(mode, ne, ki) {
  if (mode === 'table2') return lookupKrTable2(ne, ki);
  return lookupKrTable1(ne, ki);
}
